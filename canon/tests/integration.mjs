import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { compileCanon, canonHash, retrieveCanon, analysisSummary, reviewProposals } from '../context/layer1-model.js';
const fixture = JSON.parse(await readFile(new URL('./fixtures/layer1-ari.json', import.meta.url), 'utf8'));
const revision = await canonHash(fixture.sources);
const view = await compileCanon(fixture.sources, fixture.analysis, revision);
assert.equal(view.status, 'ready');
assert.ok(view.evidence.some(e => e.text.includes('Mira Vale would be 44')));
assert.ok(view.evidence.some(e => e.text.includes('Cato Vale would be 16')));
assert.ok(view.evidence.filter(e => e.kind === 'derived').every(e => e.text.includes('if alive')));
assert.ok(view.evidence.some(e => e.text.includes('Greyhaven stands')));
assert.ok(!view.evidence.some(e => e.text.includes('fire apprentice')));
assert.equal(view.proposals.length, 1);
assert.ok(!view.evidence.some(e => /greater healing/.test(e.text)));
const again = await compileCanon(fixture.sources, fixture.analysis, revision);
assert.deepEqual(again.proposals, view.proposals);
assert.equal(analysisSummary(again, [], view).proposalsCreated, 0);
const summary = analysisSummary(view, fixture.sources.map(s => s.id));
assert.equal(summary.entities.length, 5);
assert.equal(summary.proposalsCreated, 1);
assert.deepEqual(reviewProposals({ pendingLoreEntries: view.proposals }, revision).map(r => r.index), [0]);
assert.equal(reviewProposals({ pendingLoreEntries: view.proposals }, 'old').length, 0);
let searches = 0;
const options = { countTokens: s => Math.ceil(s.length / 4), budget: 1000, purpose: 'identity', search: async () => { searches++; return []; } };
assert.equal((await retrieveCanon(view, 'Ari enters', options)).status, 'ambiguous');
const match = await retrieveCanon(view, 'Ari Vale enters', options);
const familyQuery = await retrieveCanon(view, 'Ari Vale waits. How old would Mira and Cato be four years after 410?', { ...options, purpose: 'generation' });
assert.match(familyQuery.text, /Mira Vale would be 44/);
assert.match(familyQuery.text, /Cato Vale would be 16/);
assert.equal(match.status, 'matched');
assert.ok(match.text.includes('Mira Vale'));
assert.equal(searches, 0, 'Exact identity does not spend an embedding request');
assert.equal((await retrieveCanon(view, 'unrelated submarine', options)).status, 'no-match');
assert.equal((await retrieveCanon(view, 'Ari Vale', { ...options, budget: 1 })).status, 'unavailable');
assert.equal((await retrieveCanon({ ...view, status: 'partial' }, 'Nobody', options)).status, 'unavailable');
assert.equal((await compileCanon(fixture.sources, { entities: [], facts: [] }, revision)).status, 'partial', 'Empty analysis cannot authorize new identities');
const misassigned = structuredClone(fixture.analysis);
misassigned.facts.find(f => f.entity === 'ari-senn').entity = 'greyhaven';
assert.equal((await compileCanon(fixture.sources, misassigned, revision)).status, 'partial', 'An entity without its own usable evidence cannot complete analysis');
const townMatch = await retrieveCanon(view, 'river town', { ...options, search: async () => view.evidence.filter(e => e.entity === 'greyhaven').map(e => ({ id: e.id, score: 0.9 })) });
assert.ok(!townMatch.candidates?.includes('Greyhaven'), 'Locations cannot be admitted as character identities');
const bad = structuredClone(fixture.analysis); bad.facts.push({ entity: 'ari-vale', source: 'card:description', quote: 'Ari is immortal.', compatible: true });
assert.equal((await compileCanon(fixture.sources, bad, revision)).status, 'partial');
const sameYear = structuredClone(fixture.analysis); sameYear.timeShift = null;
assert.ok(!(await compileCanon(fixture.sources, sameYear, revision)).evidence.some(e => e.kind === 'derived'));
assert.equal((await compileCanon(fixture.sources, sameYear, revision)).status, 'partial', 'An omitted explicit world shift is incomplete analysis');
const personalSources = structuredClone(fixture.sources);
personalSources.find(s => s.id === 'card:scenario').text = personalSources.find(s => s.id === 'card:scenario').text.replace('The world is four years later, in year 414.', 'The world remains in year 410; only Ari\'s personal age is revised.');
const personalView = await compileCanon(personalSources, sameYear, revision);
assert.equal(personalView.status, 'ready');
assert.ok(personalView.evidence.some(e => e.text.includes('Mira Vale is 40')));
assert.ok(!personalView.evidence.some(e => e.kind === 'derived'), 'A personal age revision does not advance relatives or the calendar');
const originalWorld = structuredClone(fixture.analysis);
originalWorld.facts.find(f => f.quote.includes('Greyhaven stands')).phase = 'original';
assert.ok((await compileCanon(fixture.sources, originalWorld, revision)).evidence.some(e => e.text.includes('Greyhaven stands')), 'Compatible original world facts survive');
const { buildCanonQuery } = await import('../context/semantic-canon-index.js');
assert.equal(buildCanonQuery([{ mes: 'accepted response', swipes: ['rejected swipe'] }, { is_user: true, mes: 'pending input' }]), 'accepted response\npending input');
await assert.rejects(retrieveCanon(view, 'Ari', { ...options, signal: AbortSignal.abort() }));
console.log('Layer 1 shared fixture: chronology, mixed versions, family dependencies, ambiguous identity, proposal review, deduplication, budgets, cancellation, and grounded passages passed.');

const { resolveSagaAdmissions, sagaCanonEntries } = await import('../../../npc_codex/saga-canon.js');
const { applyCanonSeed, parseCanonSeed } = await import('../../../npc_codex/canon-seed.js');
const bridge = { queryCanon: (query, opts) => retrieveCanon(view, query, { ...options, purpose: 'story', ...opts }) };
const registry = [{ id: 'accepted-ari', name: 'Ari Vale', personality: 'Patient after accepted development', speech: 'Manual voice', manualProfileFields: ['speech'] }];
const admissions = await resolveSagaAdmissions({ npcs: [{ name: 'Ari' }, { name: 'Ari Vale' }, { name: 'Zora Newcomer' }] }, registry, { bridge });
assert.deepEqual(admissions.npcs.map(n => n.name), ['Ari Vale', 'Zora Newcomer']);
assert.equal(admissions.npcs[0].id, 'accepted-ari');
const unknown = await resolveSagaAdmissions({ npcs: [{ name: 'Zora Newcomer' }] }, [], { bridge: { queryCanon: async () => ({ status: 'unavailable' }) } });
assert.equal(unknown.npcs.length, 0);
const canon = sagaCanonEntries(match).find(e => e.comment === 'Ari Vale');
const extracted = parseCanonSeed({ personality: 'deliberate', speech: 'Invented voice', species: 'immortal dragon' }, canon.content, { strict: true });
assert.ok(extracted.rejected.includes('speech') && extracted.rejected.includes('species'));
const filled = applyCanonSeed(registry[0], { personality: 'deliberate', speech: 'soft-spoken', background: 'healer' });
assert.equal(filled.npc.personality, registry[0].personality);
assert.equal(filled.npc.speech, registry[0].speech);
assert.equal(filled.npc.background, 'healer');
const dead = { ...registry[0], lifeState: 'deceased', lifeStateCertainty: 'explicit' };
assert.equal(applyCanonSeed(dead, { background: 'healer' }).seeded.length, 0);
assert.ok(!admissions.npcs.some(n => /Mira|Cato/.test(n.name)), 'Mentioned relatives do not create dossiers');
console.log('Shared fixture NPC adapter: identity deferral, existing dossier reuse, supported seeding, manual locks, accepted development, terminal death, and no relative fan-out passed.');

